//! The bundler's part of the TypeScript declarations of `.nsh/types` (the
//! rest is nsh's modules', from `nsh_js::type_definitions`): what the asset
//! imports the bundler loads give (`assets.d.ts`). Apps find them through
//! their `tsconfig.json` ([`TSCONFIG`], extending [`TSCONFIG_BASE`]) and
//! need no `node_modules`.

/// `tsconfig.json` of a new app (`nsh init`): nsh's settings come from
/// [`TSCONFIG_BASE`], which every command that builds the app writes to
/// `.nsh/tsconfig.json`, so a new `lib` or path reaches existing apps
/// without an edit of theirs; the app's own settings go here, over them.
pub const TSCONFIG: &str = r#"{
  "extends": "./.nsh/tsconfig.json",
  "include": ["**/*.ts", "**/*.tsx"]
}
"#;

/// `.nsh/tsconfig.json`, which the app's `tsconfig.json` ([`TSCONFIG`])
/// extends: resolves `nsh` and the app's own native modules (`nsh.json`
/// `"rust"`) to `.nsh/types` (other imports fall back to `node_modules`),
/// JSX to nsh's (`nsh/jsx-runtime`), and declares the globals and asset
/// imports. Paths and files are relative to `.nsh`, where it is.
pub const TSCONFIG_BASE: &str = r#"// Generated by nsh, which keeps it current: the TypeScript settings of
// an nsh app. The app's tsconfig.json extends it; set your own there.
{
  "compilerOptions": {
    "target": "ES2023",
    "lib": ["ES2023", "ESNext.Disposable"],
    "module": "ESNext",
    "moduleResolution": "Bundler",
    "jsx": "preserve",
    "jsxImportSource": "nsh",
    "strict": true,
    "noEmit": true,
    "isolatedModules": true,
    "skipLibCheck": true,
    "types": [],
    "paths": {
      "nsh": ["./types/nsh/index.d.ts"],
      "nsh/*": ["./types/nsh/*.d.ts"],
      "*": ["./types/*.d.ts"]
    }
  },
  "files": ["./types/nsh/globals.d.ts", "./types/nsh/assets.d.ts"]
}
"#;

/// The bundler's files of `.nsh/types`.
pub fn type_definitions() -> Vec<(String, String)> {
    vec![("nsh/assets.d.ts".to_owned(), assets())]
}

/// `assets.d.ts`: what importing an image or a font gives (`plugin.rs`).
fn assets() -> String {
    use std::fmt::Write as _;
    let mut out = String::from("// Generated by nsh: what asset imports give.\n");
    for ext in crate::plugin::IMAGE_EXTENSIONS {
        let _ = write!(
            out,
            "\ndeclare module \"*.{ext}\" {{\n  /** The image, sized in points (`@2x` files at half their pixels). Imported without a density suffix, its `@1.5x`–`@4x` siblings ship too (in `scales`) and the one for the screen loads. */\n  const asset: import(\"./types\").ImageAsset;\n  export default asset;\n}}\n"
        );
    }
    for ext in crate::plugin::FONT_EXTENSIONS {
        let _ = write!(
            out,
            "\ndeclare module \"*.{ext}\" {{\n  /** The font's family name (for `fontFamily`); the font is registered before the first frame. */\n  const family: string;\n  export default family;\n}}\n"
        );
    }
    out
}

#[cfg(test)]
mod tests {
    #[test]
    fn asset_imports_are_declared() {
        let assets = super::assets();
        assert!(assets.contains("declare module \"*.png\""));
        assert!(assets.contains("declare module \"*.ttf\""));
    }

    #[test]
    fn variant_types_image_modules_describe_variants() {
        let assets = super::assets();
        for ext in crate::plugin::IMAGE_EXTENSIONS {
            let module = format!("declare module \"*.{ext}\" {{");
            let at = assets.find(&module).expect(ext);
            let block = &assets[at..at + assets[at..].find("\n}\n").unwrap()];
            assert!(
                block.contains("its `@1.5x`–`@4x` siblings ship too (in `scales`)"),
                "{block}"
            );
            assert!(block.contains("import(\"./types\").ImageAsset"), "{block}");
        }
    }
}
