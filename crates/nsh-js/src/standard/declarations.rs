//! Standard-module declarations projected from pinned LLRT source assets.
//!
//! Public value names come from the runtime registry, never from the broader
//! upstream declaration surface. The source signatures stay upstream-owned.

use std::{collections::BTreeSet, fmt::Write as _};

const PREFIX: &str = "@nsh/llrt-types/";
const BANNER: &str = "// Generated by nsh from pinned LLRT sources; do not edit.\n";
const SOURCES: &[(&str, &str)] = &[
    (
        "assert",
        include_str!("../../third_party/llrt-types/assert.d.ts.txt"),
    ),
    (
        "buffer",
        include_str!("../../third_party/llrt-types/buffer.d.ts.txt"),
    ),
    (
        "crypto",
        include_str!("../../third_party/llrt-types/crypto.d.ts.txt"),
    ),
    (
        "events",
        include_str!("../../third_party/llrt-types/events.d.ts.txt"),
    ),
    (
        "path",
        include_str!("../../third_party/llrt-types/path.d.ts.txt"),
    ),
    (
        "string_decoder",
        include_str!("../../third_party/llrt-types/string_decoder.d.ts.txt"),
    ),
    (
        "url",
        include_str!("../../third_party/llrt-types/url.d.ts.txt"),
    ),
    (
        "util",
        include_str!("../../third_party/llrt-types/util.d.ts.txt"),
    ),
    (
        "zlib",
        include_str!("../../third_party/llrt-types/zlib.d.ts.txt"),
    ),
];
const GLOBALS: &str = include_str!("../../third_party/llrt-types/globals.d.ts.txt");
#[derive(Clone, Copy)]
struct Token<'a> {
    text: &'a str,
    start: usize,
    end: usize,
}

// A lexical scanner, not a TypeScript parser: only declaration boundaries and
// top-level value names are needed. Signatures are copied without interpreting
// them. Comments, string literals and nested braces cannot create fake exports.
fn tokens(source: &str) -> Vec<Token<'_>> {
    let bytes = source.as_bytes();
    let mut out = Vec::new();
    let mut index = 0;
    while index < bytes.len() {
        if bytes[index].is_ascii_whitespace() {
            index += 1;
            continue;
        }
        if bytes[index..].starts_with(b"//") {
            while index < bytes.len() && bytes[index] != b'\n' {
                index += 1;
            }
            continue;
        }
        if bytes[index..].starts_with(b"/*") {
            index += 2;
            while index + 1 < bytes.len() && !bytes[index..].starts_with(b"*/") {
                index += 1;
            }
            index = (index + 2).min(bytes.len());
            continue;
        }
        let start = index;
        if matches!(bytes[index], b'\'' | b'"' | b'`') {
            let quote = bytes[index];
            index += 1;
            while index < bytes.len() {
                if bytes[index] == b'\\' {
                    index = (index + 2).min(bytes.len());
                } else if bytes[index] == quote {
                    index += 1;
                    break;
                } else {
                    index += 1;
                }
            }
        } else if bytes[index].is_ascii_alphanumeric() || matches!(bytes[index], b'_' | b'$') {
            index += 1;
            while index < bytes.len()
                && (bytes[index].is_ascii_alphanumeric() || matches!(bytes[index], b'_' | b'$'))
            {
                index += 1;
            }
        } else {
            // Non-ASCII characters occur inside upstream strings/comments. The
            // fallback still advances by a character to preserve UTF-8 slices.
            index += source[index..].chars().next().unwrap().len_utf8();
        }
        out.push(Token {
            text: &source[start..index],
            start,
            end: index,
        });
    }
    out
}

fn closing(tokens: &[Token<'_>], open: usize) -> usize {
    let mut depth = 0;
    for (index, token) in tokens.iter().enumerate().skip(open) {
        match token.text {
            "{" => depth += 1,
            "}" => {
                depth -= 1;
                if depth == 0 {
                    return index;
                }
            }
            _ => {}
        }
    }
    panic!("unterminated pinned LLRT declaration");
}

fn module_bodies(source: &str) -> Vec<&str> {
    let lexed = tokens(source);
    let mut out = Vec::new();
    let mut index = 0;
    while index + 3 < lexed.len() {
        if lexed[index].text == "declare"
            && lexed[index + 1].text == "module"
            && lexed[index + 3].text == "{"
        {
            let end = closing(&lexed, index + 3);
            out.push(&source[lexed[index].start..lexed[end].end]);
            index = end + 1;
        } else {
            index += 1;
        }
    }
    out
}

fn value_names(source: &str) -> BTreeSet<String> {
    let lexed = tokens(source);
    let mut depth = 0;
    let mut names = BTreeSet::new();
    for (index, token) in lexed.iter().enumerate() {
        match token.text {
            "{" => depth += 1,
            "}" => depth -= 1,
            "function" | "class" | "const" | "let" | "var" if depth == 1 => {
                if let Some(name) = lexed.get(index + 1) {
                    names.insert(name.text.to_owned());
                }
            }
            "default" if depth == 1 && index > 0 && lexed[index - 1].text == "export" => {
                names.insert("default".to_owned());
            }
            _ => {}
        }
    }
    names
}

fn remove_global_blocks(source: &str) -> String {
    let lexed = tokens(source);
    let mut out = String::new();
    let mut start = 0;
    let mut index = 0;
    while index + 1 < lexed.len() {
        if lexed[index].text == "global" && lexed[index + 1].text == "{" {
            let end = closing(&lexed, index + 1);
            out.push_str(&source[start..lexed[index].start]);
            start = lexed[end].end;
            index = end + 1;
        } else {
            index += 1;
        }
    }
    out.push_str(&source[start..]);
    out
}

fn path_members(source: &str) -> BTreeSet<String> {
    let lexed = tokens(source);
    let mut names = BTreeSet::new();
    if let Some(index) = lexed.windows(3).position(|part| {
        part[0].text == "interface" && part[1].text == "PlatformPath" && part[2].text == "{"
    }) {
        let end = closing(&lexed, index + 2);
        let mut depth = 0;
        for at in index + 2..end {
            match lexed[at].text {
                "{" => depth += 1,
                "}" => depth -= 1,
                name if depth == 1 && matches!(lexed[at + 1].text, "(" | ":") => {
                    names.insert(name.to_owned());
                }
                _ => {}
            }
        }
    }
    names
}

fn internal(source: &str) -> String {
    let mut out = remove_global_blocks(source);
    for (name, _) in SOURCES {
        out = out.replace(&format!("\"{name}\""), &format!("\"{PREFIX}{name}\""));
    }
    out
}

/// Project only reference-catalog value exports into canonical bare modules.
/// The caller supplies the standard registry's native declaration names.
pub(crate) fn type_definitions(exports: &[(&str, &[&str])]) -> Vec<(String, String)> {
    let mut source_text = String::from(BANNER);
    // QuickJS's shared byte-view aliases are upstream types, without its global
    // `performance` binding or the unrelated privileged module dependencies.
    let lexed = tokens(GLOBALS);
    if let Some(index) = lexed.windows(3).position(|part| {
        part[0].text == "namespace" && part[1].text == "QuickJS" && part[2].text == "{"
    }) {
        let end = closing(&lexed, index + 2);
        source_text.push_str("declare ");
        source_text.push_str(&GLOBALS[lexed[index].start..lexed[end].end]);
        source_text.push('\n');
    }
    let event_source = include_str!("../../third_party/llrt-types/dom-events.d.ts.txt");
    let event_tokens = tokens(event_source);
    if let Some(index) = event_tokens
        .windows(2)
        .position(|part| part[0].text == "type" && part[1].text == "EventKey")
    {
        let end = event_tokens[index..]
            .iter()
            .position(|token| token.text == ";")
            .unwrap()
            + index;
        source_text.push_str(&event_source[event_tokens[index].start..event_tokens[end].end]);
        source_text.push('\n');
    }
    for (_, source) in SOURCES {
        for body in module_bodies(source) {
            source_text.push_str(&internal(body));
            source_text.push('\n');
        }
    }
    let mut public = String::from(BANNER);
    public.push_str("/// <reference path=\"./llrt-sources.d.ts\" />\n");
    for (name, values) in exports {
        if !super::NAMES.contains(name) {
            continue;
        }
        let Some((_, source)) = SOURCES.iter().find(|(module, _)| module == name) else {
            continue;
        };
        let names = if *name == "path" {
            path_members(source)
        } else {
            value_names(source)
        };
        let _ = writeln!(public, "declare module \"{name}\" {{");
        if *name == "path" {
            let _ = writeln!(
                public,
                "  export type {{ ParsedPath, FormatInputPathObject, PlatformPath }} from \"{PREFIX}{name}\";"
            );
        } else {
            let _ = writeln!(public, "  export type * from \"{PREFIX}{name}\";");
        }
        for value in *values {
            if *value == "default" {
                continue;
            }
            if names.contains(*value) && *name != "path" {
                let _ = writeln!(public, "  export {{ {value} }} from \"{PREFIX}{name}\";");
            } else if *name == "path" && names.contains(*value) {
                let _ = writeln!(
                    public,
                    "  export const {value}: typeof import(\"{PREFIX}{name}\").{value};"
                );
            } else {
                let _ = writeln!(
                    public,
                    "  /** Native LLRT value without an upstream signature. */\n  export const {value}: unknown;"
                );
            }
        }
        if values.contains(&"default") {
            if names.contains("default") {
                let _ = writeln!(public, "  export {{ default }} from \"{PREFIX}{name}\";");
            } else if *name == "assert" {
                let _ = writeln!(
                    public,
                    "  export {{ assert as default }} from \"{PREFIX}{name}\";"
                );
            } else {
                public.push_str("  const defaultExport: {\n");
                for value in *values {
                    if *value != "default" {
                        let _ = writeln!(public, "    {value}: typeof import(\"{name}\").{value};");
                    }
                }
                public.push_str("  };\n  export default defaultExport;\n");
            }
        }
        public.push_str("}\n");
    }
    adapter(&mut public, "console", super::console::TYPES);
    vec![
        ("standard/llrt-sources.d.ts".into(), source_text),
        ("standard/index.d.ts".into(), public),
    ]
}

fn adapter(out: &mut String, name: &str, body: &str) {
    // Adapter metadata is also valid as an external declaration file; nested
    // ambient modules omit its redundant top-level `declare` modifiers.
    let body = body
        .lines()
        .map(|line| line.strip_prefix("declare ").unwrap_or(line))
        .collect::<Vec<_>>()
        .join("\n");
    let _ = writeln!(out, "declare module \"{name}\" {{\n{body}\n}}");
}

/// New standard globals derive their types from the same projected signatures
/// as their module imports. Existing WHATWG globals remain NSH-owned.
pub(crate) fn globals() -> String {
    String::from(
        r#"
declare var Buffer: typeof import("buffer").Buffer;
type Buffer = import("buffer").Buffer;
declare var process: typeof import("process").default;
declare var crypto: Pick<typeof import("crypto").default, "createHash" | "createHmac" | "randomBytes" | "randomInt" | "randomUUID" | "randomFill" | "randomFillSync" | "getRandomValues"> & { readonly subtle: typeof import("@nsh/llrt-types/crypto").subtle };
/** Runtime constructor without an upstream constructor signature. */
declare const Crypto: unknown;
/** Runtime constructor without an upstream constructor signature. */
declare const CryptoKey: unknown;
/** Runtime constructor without an upstream constructor signature. */
declare const SubtleCrypto: unknown;
"#,
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn upstream_values_are_detected_without_nested_types_or_comment_examples() {
        let util = SOURCES.iter().find(|(name, _)| *name == "util").unwrap().1;
        let values = value_names(util);
        assert!(values.contains("format"));
        assert!(values.contains("TextDecoder"));
        assert!(!values.contains("onmessage"));
        let buffer = SOURCES
            .iter()
            .find(|(name, _)| *name == "buffer")
            .unwrap()
            .1;
        assert!(value_names(buffer).contains("Buffer"));
    }

    #[test]
    fn projections_do_not_promote_unimplemented_upstream_values() {
        let files = type_definitions(&[("url", &["URL", "default"])]);
        let public = &files[1].1;
        assert!(public.contains("export { URL }"));
        assert!(public.contains("declare module \"url\""));
        assert!(!public.contains("export { parse }"));
        assert!(!public.contains("declare module \"node:"));
    }

    #[test]
    fn source_globals_do_not_replace_nsh_web_globals() {
        let files = type_definitions(&[]);
        let source = &files[0].1;
        assert!(source.contains("declare namespace QuickJS"));
        assert!(!source.contains("declare global"));
        assert!(!source.contains("var performance"));
        assert!(!source.contains("from \"perf_hooks\""));
    }
}
